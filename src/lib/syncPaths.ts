export interface FileManifest {
  [filePath: string]: {
    size: number;
    mtime: number;
  };
}

/** True if a vault-relative path falls inside the given shared folder. An empty sharedFolder means "not configured" -- never in scope. */
export function isWithinSharedFolder(sharedFolder: string, vaultRelPath: string): boolean {
  if (!sharedFolder) return false;
  const normalized = vaultRelPath.replace(/\\/g, '/');
  const folder = sharedFolder.replace(/\/+$/, '');
  return normalized === folder || normalized.startsWith(folder + '/');
}

/** Vault-relative path -> path relative to the shared folder, as sent on the wire. */
export function toWireRelPath(sharedFolder: string, vaultRelPath: string): string {
  const normalized = vaultRelPath.replace(/\\/g, '/');
  if (!sharedFolder) return normalized;
  const prefix = sharedFolder.replace(/\/+$/, '') + '/';
  return normalized.startsWith(prefix) ? normalized.slice(prefix.length) : normalized;
}

/** Inverse of toWireRelPath. */
export function toVaultRelPath(sharedFolder: string, wireRelPath: string): string {
  if (!sharedFolder) return wireRelPath;
  return `${sharedFolder.replace(/\/+$/, '')}/${wireRelPath}`;
}

/**
 * Filter mechanism to ignore temporary, transient, or large system files that
 * cause conflict spam or should not be synced.
 */
export function shouldIgnore(path: string): boolean {
  const normalized = path.replace(/\\/g, '/');

  // Ephemeral/System directories
  if (
    normalized.startsWith('.git/') || normalized === '.git' ||
    normalized.startsWith('.trash/') || normalized === '.trash' ||
    normalized.startsWith('node_modules/') || normalized === 'node_modules' ||
    normalized.startsWith('Sync Conflicts/') || normalized === 'Sync Conflicts'
  ) {
    return true;
  }

  // Plugin internal data (room state binaries, backups, etc.)
  if (normalized.includes('.obsidian/plugins/lanote/data/')) {
    return true;
  }

  // Conflict copy files (generated by previous sync versions)
  if (normalized.includes('(Conflict from ')) {
    return true;
  }

  // Specific noise files and device-specific workspace configurations
  if (
    normalized.includes('.obsidian/workspace') || // covers workspace.json, workspace-mobile.json, workspaces.json, etc.
    normalized.endsWith('/.DS_Store') || normalized === '.DS_Store' ||
    normalized.endsWith('/thumbs.db') || normalized === 'thumbs.db'
  ) {
    return true;
  }

  return false;
}
